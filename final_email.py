import re
import os

def analyze_email():
    print("================================================")
    print("              EMAIL RISK ANALYZER")
    print("================================================")

    print("\n--- ENTER EMAIL DETAILS FOR ANALYSIS ---")
    sender = input("From (Sender Email, e.g., security@paypal-secure.com): ").strip()
    return_path = input("Return-Path (e.g., hacker@gmail.com): ").strip()
    spf_status = input("SPF Status (PASS / FAIL / NONE): ").strip().upper()
    dkim_status = input("DKIM Status (PASS / FAIL / NONE): ").strip().upper()
    
    print("\nEnter Email Body Text (Type or paste the email content):")
    body_text = input("> ")

    risk_score = 0
    flags = []

    sender_domain = sender.split('@')[-1] if '@' in sender else ""
    return_domain = return_path.split('@')[-1] if '@' in return_path else ""

    if sender_domain != return_domain:
        risk_score += 30
        flags.append("Domain Spoofing Detected (From and Return-Path do not match)")

    if spf_status == "FAIL":
        risk_score += 25
        flags.append("SPF Authentication Failed")
    elif spf_status == "NONE":
        risk_score += 10
        flags.append("Missing SPF Record")

    if dkim_status == "FAIL":
        risk_score += 25
        flags.append("DKIM Authentication Failed")

    urgent_keywords = ["urgent", "action required", "verify your account", "suspend", "login immediately", "password reset", "click here"]
    found_keywords = [word for word in urgent_keywords if word in body_text.lower()]
    
    if found_keywords:
        risk_score += len(found_keywords) * 10
        flags.append(f"Urgent action/phishing keywords found: {', '.join(found_keywords)}")

    if "http://" in body_text.lower() or ".com" in body_text.lower() and ("login" in body_text.lower() or "secure" in body_text.lower()):
        risk_score += 15
        flags.append("Suspicious link structure or keywords in body")

    risk_score = min(risk_score, 100) 
    if risk_score < 30:
        verdict = "LOW RISK (Safe Email)"
    elif risk_score < 70:
        verdict = "MODERATE RISK (Suspicious)"
    else:
        verdict = "HIGH RISK (Potential Phishing Attack!)"

    print("\n================================================")
    print("            SECURITY AUDIT REPORT")
    print("================================================")
    print(f"Sender Domain: {sender_domain}")
    print(f"Overall Risk Score: {risk_score}/100")
    print(f"Verdict: {verdict}")
    print("\nDetected Risk Factors:")
    if flags:
        for flag in flags:
            print(f"- {flag}")
    else:
        print("- No obvious phishing indicators detected.")
    print("================================================")

    report_filename = "Phishing_Analysis_Report.txt"
    with open(report_filename, "w", encoding="utf-8") as f:
        f.write("================================================\n")
        f.write("          EMAIL PHISHING ANALYSIS REPORT        \n")
        f.write("================================================\n\n")
        f.write(f"Sender: {sender}\n")
        f.write(f"Return-Path: {return_path}\n")
        f.write(f"SPF Record: {spf_status} | DKIM Record: {dkim_status}\n")
        f.write(f"Risk Score: {risk_score}/100\n")
        f.write(f"Security Verdict: {verdict}\n\n")
        f.write("--- DETECTED RISK FACTORS ---\n")
        for flag in flags:
            f.write(f"[!] {flag}\n")
        if not flags:
            f.write("[-] No standard threat vectors identified.\n")
        f.write("\n================================================\n")
        f.write("Generated by Email Risk Analyzer Utility\n")

    print(f"\n[SUCCESS] Audit Report saved as '{report_filename}' on your computer.")

if __name__ == "__main__":
    analyze_email()
